package com.pwaquatics.shop.catalog.application;

import com.pwaquatics.shop.catalog.application.view.CareView;
import com.pwaquatics.shop.catalog.application.view.CategoryRef;
import com.pwaquatics.shop.catalog.application.view.ColourView;
import com.pwaquatics.shop.catalog.application.view.GradeRef;
import com.pwaquatics.shop.catalog.application.view.GradeView;
import com.pwaquatics.shop.catalog.application.view.SpeciesRef;
import com.pwaquatics.shop.catalog.application.view.SpeciesSummaryView;
import com.pwaquatics.shop.catalog.application.view.SpeciesView;
import com.pwaquatics.shop.catalog.domain.Category;
import com.pwaquatics.shop.catalog.domain.Colour;
import com.pwaquatics.shop.catalog.domain.Grade;
import com.pwaquatics.shop.catalog.domain.Species;
import com.pwaquatics.shop.common.text.Markdown;
import org.mapstruct.Mapper;
import org.mapstruct.Mapping;

/** Entity → view mappings without business logic (generated by MapStruct). */
@Mapper(imports = Markdown.class)
interface CatalogViewMapper {

    ColourView toView(Colour colour);

    GradeView toView(Grade grade);

    GradeRef toRef(Grade grade);

    CategoryRef toRef(Category category);

    SpeciesRef toRef(Species species);

    SpeciesSummaryView toSummary(Species species);

    @Mapping(target = "descriptionHtml", expression = "java(Markdown.toSafeHtml(species.getDescription()))")
    @Mapping(target = "care", source = ".")
    SpeciesView toView(Species species);

    CareView toCare(Species species);
}
